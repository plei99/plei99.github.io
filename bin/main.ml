let write_file path contents =
  let dir = Filename.dirname path in
  if not (Sys.file_exists dir) then Unix.mkdir dir 0o755;
  let output = open_out path in
  Fun.protect
    ~finally:(fun () -> close_out output)
    (fun () -> output_string output contents)

let assoc_string key fields =
  match List.assoc_opt key fields with
  | Some (`String value) -> value
  | _ -> ""

let read_site path =
  match Yaml_unix.of_file_exn (Fpath.v path) with
  | `O fields -> (assoc_string "name" fields, assoc_string "subtitle" fields)
  | _ -> failwith "data/site.yaml must be a YAML object"

let () =
  let site_name, site_subtitle = read_site "data/site.yaml" in
  let content =
    {|
      <div class="hero">
        <p class="hero-label">Welcome</p>
        <h1 class="hero-name"><strong>Hi, I'm Patrick.</strong><br>I do mathematics.</h1>
        <p class="hero-sub">
          This page is generated by the new OCaml static site generator.
        </p>
      </div>
    |}
  in
  let html =
    Jingoo.Jg_template.from_file "templates/base.html"
      ~models:
        [
          ("lang", Jingoo.Jg_types.Tstr "en");
          ("title", Jingoo.Jg_types.Tstr site_name);
          ("site_name", Jingoo.Jg_types.Tstr site_name);
          ("site_subtitle", Jingoo.Jg_types.Tstr site_subtitle);
          ( "nav_html",
            Jingoo.Jg_types.Tsafe
              {|
      <span class="nav-section-label">Research</span>
      <a href="/papers.html" class="nav-link">Papers</a>
      <a href="/notes.html" class="nav-link">Notes</a>|} );
          ("footer_html", Jingoo.Jg_types.Tsafe "© 2026 Patrick Lei<br><a href=\"https://github.com/plei99/plei99.github.io\">Source</a>");
          ("content", Jingoo.Jg_types.Tsafe content);
        ]
  in
  write_file "public/index.html" html
